CREATE TABLE IF NOT EXISTS usuarios (
  id UUID PRIMARY KEY,
  email VARCHAR(320) NOT NULL UNIQUE,
  nombre VARCHAR(160) NOT NULL,
  password_hash TEXT NOT NULL,
  activo BOOLEAN NOT NULL DEFAULT TRUE,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  actualizado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT usuarios_email_no_vacio CHECK (length(trim(email)) > 3),
  CONSTRAINT usuarios_nombre_no_vacio CHECK (length(trim(nombre)) > 0)
);

CREATE INDEX IF NOT EXISTS usuarios_activo_idx ON usuarios (activo);

CREATE TABLE IF NOT EXISTS conductores (
  id UUID PRIMARY KEY,
  usuario_id UUID NOT NULL UNIQUE,
  licencia_numero VARCHAR(64) NOT NULL UNIQUE,
  licencia_expira_en DATE NOT NULL,
  disponible BOOLEAN NOT NULL DEFAULT FALSE,
  activo BOOLEAN NOT NULL DEFAULT TRUE,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  actualizado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT conductores_licencia_no_vacia CHECK (length(trim(licencia_numero)) > 0)
);

CREATE INDEX IF NOT EXISTS conductores_disponible_idx
  ON conductores (disponible) WHERE activo = TRUE;

CREATE TABLE IF NOT EXISTS vehiculos (
  id UUID PRIMARY KEY,
  conductor_id UUID NOT NULL UNIQUE,
  patente VARCHAR(16) NOT NULL UNIQUE,
  marca VARCHAR(80) NOT NULL,
  modelo VARCHAR(80) NOT NULL,
  anio SMALLINT NOT NULL,
  capacidad SMALLINT NOT NULL DEFAULT 4,
  activo BOOLEAN NOT NULL DEFAULT TRUE,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  actualizado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT vehiculos_patente_no_vacia CHECK (length(trim(patente)) > 0),
  CONSTRAINT vehiculos_anio_valido CHECK (anio BETWEEN 1950 AND 2200),
  CONSTRAINT vehiculos_capacidad_valida CHECK (capacidad BETWEEN 1 AND 20)
);

CREATE INDEX IF NOT EXISTS vehiculos_activo_idx ON vehiculos (activo);

CREATE TABLE IF NOT EXISTS ubicaciones (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  conductor_id UUID NOT NULL,
  latitud NUMERIC(9, 6) NOT NULL,
  longitud NUMERIC(9, 6) NOT NULL,
  precision_metros NUMERIC(8, 2),
  registrada_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT ubicaciones_latitud_valida CHECK (latitud BETWEEN -90 AND 90),
  CONSTRAINT ubicaciones_longitud_valida CHECK (longitud BETWEEN -180 AND 180),
  CONSTRAINT ubicaciones_precision_valida CHECK (precision_metros IS NULL OR precision_metros >= 0)
);

CREATE INDEX IF NOT EXISTS ubicaciones_conductor_fecha_idx
  ON ubicaciones (conductor_id, registrada_en DESC);

CREATE TABLE IF NOT EXISTS estados_viaje (
  codigo VARCHAR(32) PRIMARY KEY,
  descripcion VARCHAR(160) NOT NULL,
  terminal BOOLEAN NOT NULL DEFAULT FALSE
);

INSERT INTO estados_viaje (codigo, descripcion, terminal) VALUES
  ('REQUESTED', 'Trip requested', FALSE),
  ('DISPATCHING', 'Looking for a driver', FALSE),
  ('ASSIGNED', 'Driver assigned', FALSE),
  ('DRIVER_ARRIVING', 'Driver arriving at origin', FALSE),
  ('IN_PROGRESS', 'Trip in progress', FALSE),
  ('COMPLETED', 'Trip completed', TRUE),
  ('NO_DRIVERS_AVAILABLE', 'No driver found', TRUE),
  ('CANCELLED', 'Trip cancelled', TRUE)
ON CONFLICT (codigo) DO NOTHING;

CREATE TABLE IF NOT EXISTS historial_estados_viaje (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  viaje_id UUID NOT NULL,
  estado VARCHAR(32) NOT NULL REFERENCES estados_viaje (codigo),
  actor_id UUID,
  motivo VARCHAR(500),
  ocurrido_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS historial_estados_viaje_idx
  ON historial_estados_viaje (viaje_id, ocurrido_en DESC);

CREATE TABLE IF NOT EXISTS pagos (
  id UUID PRIMARY KEY,
  viaje_id UUID NOT NULL,
  pasajero_id UUID NOT NULL,
  monto INTEGER NOT NULL,
  moneda CHAR(3) NOT NULL DEFAULT 'ARS',
  estado VARCHAR(16) NOT NULL DEFAULT 'PENDING',
  proveedor_referencia VARCHAR(200),
  creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  actualizado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT pagos_monto_valido CHECK (monto > 0),
  CONSTRAINT pagos_moneda_valida CHECK (moneda IN ('ARS')),
  CONSTRAINT pagos_estado_valido CHECK (estado IN ('PENDING', 'CAPTURED', 'FAILED', 'REFUNDED')),
  CONSTRAINT pagos_viaje_unico UNIQUE (viaje_id)
);

CREATE INDEX IF NOT EXISTS pagos_pasajero_idx ON pagos (pasajero_id);
CREATE INDEX IF NOT EXISTS pagos_estado_idx ON pagos (estado);
